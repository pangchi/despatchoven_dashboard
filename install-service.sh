#!/usr/bin/env bash
# Install the dashboard as a systemd service, running from the folder this script is in
# (e.g. /opt/oven-dashboard) with its existing venv and .env. Run ./setup.sh first.
#
#   sudo ./install-service.sh                     install / update and start the service
#   sudo ./install-service.sh --port 8080         listen on another port (default 8000)
#   sudo ./install-service.sh --user ovendash     run as this user (created if missing; default: the sudo user)
#   sudo ./install-service.sh --name oven         service name (default: folder name, e.g. oven-dashboard)
#   sudo ./install-service.sh --no-start          install and enable, but do not start now
#   ./install-service.sh --dry-run                print the unit file, change nothing
#   sudo ./install-service.sh --uninstall         stop, disable and remove the service
#
# Safe to re-run: the unit file is rewritten and the service restarted.
set -euo pipefail

APP_DIR=$(cd "$(dirname "$(readlink -f "$0")")" && pwd)
NAME=$(basename "$APP_DIR")
PORT=8000
RUN_USER=${SUDO_USER:-}
START=1 DRY_RUN=0 UNINSTALL=0

while [ $# -gt 0 ]; do
  case "$1" in
    --port) shift; PORT=${1:?--port needs a number} ;;
    --user) shift; RUN_USER=${1:?--user needs a name} ;;
    --name) shift; NAME=${1:?--name needs a value} ;;
    --no-start) START=0 ;;
    --dry-run) DRY_RUN=1 ;;
    --uninstall) UNINSTALL=1 ;;
    -h|--help) awk 'NR>1 && /^#/ {sub(/^# ?/, ""); print; next} NR>1 {exit}' "$0"; exit 0 ;;
    *) echo "Unknown option: $1 (see --help)" >&2; exit 2 ;;
  esac
  shift
done

say()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mWARN:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

[[ "$NAME" =~ ^[A-Za-z0-9_.@-]+$ ]] || die "invalid service name: $NAME"
[[ "$PORT" =~ ^[0-9]+$ ]] && [ "$PORT" -ge 1 ] && [ "$PORT" -le 65535 ] || die "invalid port: $PORT"
UNIT_FILE=/etc/systemd/system/$NAME.service

need_root() { [ "$(id -u)" = 0 ] || die "run with sudo: sudo $0 $*"; }

# ---------------------------------------------------------------- uninstall
if [ "$UNINSTALL" = 1 ]; then
  need_root --uninstall
  if [ -f "$UNIT_FILE" ]; then
    say "Stopping and removing $NAME"
    systemctl disable --now "$NAME" 2>/dev/null || true
    rm -f "$UNIT_FILE"
    systemctl daemon-reload
    systemctl reset-failed "$NAME" 2>/dev/null || true
    say "Removed. App files in $APP_DIR were left untouched."
  else
    say "No service $UNIT_FILE - nothing to remove"
  fi
  exit 0
fi

# ---------------------------------------------------------------- checks
VENV=$APP_DIR/venv
[ -x "$VENV/bin/gunicorn" ] || die "$VENV/bin/gunicorn not found - run ./setup.sh in $APP_DIR first"
[ -f "$APP_DIR/wsgi.py" ]   || die "wsgi.py not found in $APP_DIR"
[ -f "$APP_DIR/.env" ]      || die "$APP_DIR/.env not found - run ./setup.sh first"
if [ -z "$RUN_USER" ] || [ "$RUN_USER" = root ]; then
  die "pick a non-root user to run the service: sudo $0 --user <name>"
fi

env_get() { grep -E "^$1=" "$APP_DIR/.env" | tail -1 | cut -d= -f2- | sed -e "s/^['\"]//" -e "s/['\"]$//"; }
DB_HOST=$(env_get DB_HOST || true)
SERIAL_PORT=$(env_get SERIAL_PORT || true)

# Wait for a local PostgreSQL at boot
AFTER="network-online.target"; WANTS="network-online.target"
case "${DB_HOST:-localhost}" in
  localhost|127.0.0.1|::1|/*) AFTER="$AFTER postgresql.service"; WANTS="$WANTS postgresql.service" ;;
esac

UNIT=$(cat <<EOF
# Generated by install-service.sh - re-run it to change settings instead of editing here.
[Unit]
Description=Oven dashboard ($NAME) - Protocol 3 monitor
After=$AFTER
Wants=$WANTS

[Service]
Type=simple
User=$RUN_USER
Group=$RUN_USER
# dialout = access to the RS-485 adapter (/dev/ttyUSB*, /dev/ttyAMA*)
SupplementaryGroups=dialout
WorkingDirectory=$APP_DIR
Environment=PYTHONUNBUFFERED=1
# ONE worker only: the poller thread owns the serial port
ExecStart=$VENV/bin/gunicorn -w 1 --threads 4 -b 0.0.0.0:$PORT --timeout 60 --graceful-timeout 10 --access-logfile - wsgi:app
Restart=always
RestartSec=5
TimeoutStopSec=20
NoNewPrivileges=true
ProtectSystem=full
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
)

if [ "$DRY_RUN" = 1 ]; then
  say "Dry run - would write $UNIT_FILE:"
  echo "$UNIT"
  exit 0
fi
need_root

# ---------------------------------------------------------------- user & permissions
if ! id "$RUN_USER" >/dev/null 2>&1; then
  say "Creating system user $RUN_USER"
  useradd --system --home-dir "$APP_DIR" --shell /usr/sbin/nologin "$RUN_USER"
fi
if ! id -nG "$RUN_USER" | tr ' ' '\n' | grep -qx dialout; then
  say "Adding $RUN_USER to group dialout (serial port access)"
  usermod -aG dialout "$RUN_USER"
fi

OWNER=$(stat -c %U "$APP_DIR/.env")
if [ "$OWNER" != "$RUN_USER" ]; then
  say "Giving $RUN_USER ownership of $APP_DIR (was $OWNER)"
  chown -R "$RUN_USER:$RUN_USER" "$APP_DIR"
fi
chmod 600 "$APP_DIR/.env"

if [ "${SERIAL_PORT:-}" != "SIMULATOR" ] && [ -n "${SERIAL_PORT:-}" ] && [ ! -e "$SERIAL_PORT" ]; then
  warn "SERIAL_PORT=$SERIAL_PORT does not exist right now - the service will start and keep retrying"
fi
if command -v ss >/dev/null && ss -ltnH "sport = :$PORT" | grep -q . && ! systemctl is-active -q "$NAME"; then
  warn "port $PORT is already in use by another program:"
  ss -ltnpH "sport = :$PORT" >&2 || true
fi
for other in protocol3-monitor; do
  if [ "$other" != "$NAME" ] && systemctl is-enabled -q "$other" 2>/dev/null; then
    warn "service '$other' is also enabled - two copies would fight over the serial port."
    warn "  disable it:  sudo systemctl disable --now $other"
  fi
done

# ---------------------------------------------------------------- install
say "Writing $UNIT_FILE"
printf '%s\n' "$UNIT" > "$UNIT_FILE"
systemctl daemon-reload
systemctl enable -q "$NAME"
say "Enabled $NAME (starts at boot)"

if [ "$START" = 0 ]; then
  say "Not started (--no-start). Start with: sudo systemctl start $NAME"
  exit 0
fi

say "Starting $NAME"
systemctl restart "$NAME"

# ---------------------------------------------------------------- health check
say "Waiting for http://127.0.0.1:$PORT/api/v1/health"
HEALTH=""
for _ in $(seq 1 30); do
  sleep 1
  systemctl is-active -q "$NAME" || break
  HEALTH=$("$VENV/bin/python" -c "
import urllib.request, sys
try:
    print(urllib.request.urlopen('http://127.0.0.1:$PORT/api/v1/health', timeout=2).read().decode())
except Exception:
    sys.exit(1)" 2>/dev/null) && break
done

if [ -n "$HEALTH" ]; then
  say "Running: $HEALTH"
  case "$HEALTH" in *'"comm_ok":false'*)
    warn "web app is up but the controller is not answering yet - check wiring / SERIAL_* in .env" ;;
  esac
  IP=$(hostname -I 2>/dev/null | awk '{print $1}')
  cat <<EOF

Dashboard:  http://${IP:-<pi-ip>}:$PORT/
Logs:       journalctl -u $NAME -f
Restart:    sudo systemctl restart $NAME      (after editing .env)
Remove:     sudo $APP_DIR/install-service.sh --uninstall
EOF
else
  warn "$NAME did not come up. Last log lines:"
  journalctl -u "$NAME" -n 30 --no-pager >&2 || true
  exit 1
fi
